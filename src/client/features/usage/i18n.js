/**
 * 取 translator，永远返回非空字符串（拼进 JSX 的 t() 返回 undefined 会整块崩）。
 *
 * 共享实现比旧插件那版多了「命名空间参数」与统一的回退策略（fallback = zh），
 * 行为一致：命名空间没注册时退回内置字典，切换语言后自动跟上。
 *
 * @param {object} locale ctx.locale 服务。
 * @returns {(key: string, vars?: Record<string, unknown>) => string} translator。
 */
export function makeTranslator(locale) {
  return sharedMakeTranslator(locale, NS, zh);
}
